"""Rendering the avahi static service file.

`avahi-daemon` reads `/etc/avahi/services/*.service` as XML fragments
(`avahi.service(5)`). The file is *static* in avahi's sense — it is
re-read on `SIGHUP` / `avahi-daemon --reload`, not watched — so the
publisher rewrites it whenever the payload changes and then asks the
daemon to reload.

Why the file is generated rather than shipped as a fixed asset: two of
the five TXT values (`ip`, `transport`) are runtime facts. The address
moves under DHCP, and the transport moves when the unit switches
between Ethernet and WiFi. A file baked into the image would advertise
a stale address — the exact failure the field guide warns about.

The rendered XML:

    <?xml version="1.0" standalone='no'?>
    <!DOCTYPE service-group SYSTEM "avahi-service.dtd">
    <service-group>
      <name replace-wildcards="yes">AquaButler on %h</name>
      <service protocol="ipv4">
        <type>_aquabutler._tcp</type>
        <port>5150</port>
        <host-name>aqb0007abcd.local</host-name>
        <txt-record>unit_id=...</txt-record>
        ...
      </service>
    </service-group>

The `<host-name>` is the unit's `<unit_id>.local` name, so
`avahi-resolve -n <unit_id>.local` returns the unit's address.
"""
from __future__ import annotations

import logging
import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

from .identity import SERVICE_PORT, SERVICE_TYPE, Advertisement


log = logging.getLogger(__name__)


# Default location of the generated service file inside the container.
DEFAULT_SERVICE_FILE = Path("/etc/avahi/services/aquabutler.service")

# XML 1.0 forbids most control characters; avahi's TXT values are
# plain text, so strip anything that cannot legally appear in XML.
# The avahi service file is line-oriented: one <txt-record> per line.
# A newline inside a value would split one record into two malformed
# ones, so line breaks are removed outright rather than escaped.
# XML also forbids most control characters; the remainder are stripped.
_XML_ILLEGAL_RE = re.compile(
    "[^\x20-\ud7ff\ue000-\ufffd\U00010000-\U0010ffff]"
)


def xml_escape(value: str) -> str:
    """Escape a value for inclusion in the rendered XML."""
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def sanitize_txt_value(value: str) -> str:
    """Strip characters that cannot legally appear in an XML document.

    A TXT value is transmitted verbatim, so a stray newline or NUL
    would corrupt the service file. Only printable ASCII and sane
    Unicode survive.
    """
    if not value:
        return ""
    return _XML_ILLEGAL_RE.sub("", value)


@dataclass(frozen=True)
class ServiceDefinition:
    """The parsed shape of an avahi service file.

    Parsing the rendered file back (rather than trusting the
    in-memory objects) is what lets the unit test assert that the
    *file on disk* carries the right type, port and TXT keys.
    """

    name: str
    service_type: str
    port: int
    host_name: str
    txt: dict[str, str]

    @property
    def txt_keys(self) -> set[str]:
        return set(self.txt)


def render_service_file(
    advertisement: Advertisement,
    host_name: str,
    service_name: str = "AquaButler",
) -> str:
    """Render the avahi service file for one advertisement snapshot.

    The TXT records are written in the canonical key order so the
    rendered file is stable — a stable file means an unchanged
    advertisement does not trigger a needless avahi reload.
    """
    lines = [
        "<?xml version=\"1.0\" standalone='no'?>",
        "<!DOCTYPE service-group SYSTEM \"avahi-service.dtd\">",
        "",
        "<!-- Generated by aquabutler-mdns. DO NOT EDIT BY HAND. -->",
        "<!-- The publisher rewrites this file and reloads avahi-daemon",
        "     whenever the advertised payload changes (DHCP lease move,",
        "     transport switch). -->",
        "<service-group>",
        f"  <name replace-wildcards=\"yes\">{xml_escape(service_name)} on %h</name>",
        "  <service protocol=\"ipv4\">",
        f"    <type>{xml_escape(SERVICE_TYPE)}</type>",
        f"    <port>{SERVICE_PORT}</port>",
        f"    <host-name>{xml_escape(host_name)}</host-name>",
    ]

    for key, value in advertisement.txt_records():
        clean = sanitize_txt_value(value)
        if clean == "":
            continue
        lines.append(f"    <txt-record>{xml_escape(key)}={xml_escape(clean)}</txt-record>")

    lines.append("  </service>")
    lines.append("</service-group>")
    lines.append("")
    return "\n".join(lines)


def parse_service_file(text: str) -> ServiceDefinition:
    """Parse a rendered avahi service file back into its parts.

    Raises `ValueError` when the document is not a well-formed avahi
    service group — the unit test relies on this to catch a malformed
    render.
    """
    try:
        root = ET.fromstring(text)
    except ET.ParseError as exc:
        raise ValueError(f"service file is not well-formed XML: {exc}") from exc

    if root.tag != "service-group":
        raise ValueError(f"expected a service-group root, got {root.tag!r}")

    services = root.findall("service")
    if len(services) != 1:
        raise ValueError(f"expected exactly one <service>, got {len(services)}")

    service = services[0]

    type_el = service.find("type")
    if type_el is None or not (type_el.text or "").strip():
        raise ValueError("service file has no <type>")
    service_type = type_el.text.strip()

    port_el = service.find("port")
    if port_el is None or not (port_el.text or "").strip():
        raise ValueError("service file has no <port>")
    try:
        port = int(port_el.text.strip())
    except ValueError as exc:
        raise ValueError(f"port is not an integer: {port_el.text!r}") from exc

    host_el = service.find("host-name")
    host_name = (host_el.text or "").strip() if host_el is not None else ""

    txt: dict[str, str] = {}
    for txt_el in service.findall("txt-record"):
        raw = (txt_el.text or "").strip()
        if "=" not in raw:
            raise ValueError(f"txt-record is not key=value: {raw!r}")
        key, _, value = raw.partition("=")
        key = key.strip()
        if not key:
            raise ValueError(f"txt-record has an empty key: {raw!r}")
        if key in txt:
            raise ValueError(f"duplicate txt-record key: {key!r}")
        txt[key] = value

    name_el = root.find("name")
    name = (name_el.text or "").strip() if name_el is not None else ""

    return ServiceDefinition(
        name=name,
        service_type=service_type,
        port=port,
        host_name=host_name,
        txt=txt,
    )


